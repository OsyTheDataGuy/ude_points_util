# Create function that takes two dataframes -- fight_details and previous_complete -- and returns fight_details where 'URL' is not in previous_complete['fight_url'].
def filter_new_fights_set(latest_fights: pd.DataFrame, current_dataset: pd.DataFrame) -> pd.DataFrame:
    prev_urls = set(current_dataset['fight_url'])
    mask = ~latest_fights['URL'].isin(prev_urls)
    return latest_fights.loc[mask].reset_index(drop=True)


PLAYWRIGHT = None
BROWSER = None
PAGE = None

def start_browser():
    global PLAYWRIGHT
    global BROWSER
    global PAGE

    # Imported lazily, not at module load, so filter_new_fights_set/
    # exclude_dataless_events (pure logic, no browser needed) can be
    # imported and tested without playwright installed at all.
    from playwright.sync_api import sync_playwright

    PLAYWRIGHT = sync_playwright().start()

    BROWSER = PLAYWRIGHT.chromium.launch(
        headless=True
    )

    PAGE = BROWSER.new_page()

    # Block images/fonts/stylesheets
    PAGE.route(
        "**/*",
        lambda route: route.abort()
        if route.request.resource_type
        in ["image", "font", "stylesheet"]
        else route.continue_()
    )


def stop_browser():
    global PLAYWRIGHT
    global BROWSER

    if BROWSER:
        BROWSER.close()

    if PLAYWRIGHT:
        PLAYWRIGHT.stop()


